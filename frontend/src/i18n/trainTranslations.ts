/**
 * Returns localized name for any train schedule or live telemetry item
 */
export function getLocalizedTrainName(
  trainName: string, 
  lang: LanguageCode, 
  trainNumber?: string
): string {
  if (lang === 'en' || !trainName) return trainName;

  // Search by trainNumber first
  if (trainNumber) {
    const cleanNum = String(trainNumber).replace(/\D/g, '');
    const foundByNum = TRAIN_TRANSLATIONS.find(t => 
      t.numbers.some(n => n.replace(/\D/g, '') === cleanNum)
    );
    if (foundByNum && foundByNum.names[lang]) {
      return foundByNum.names[lang]!;
    }
  }

  // Search by name keywords
  const lower = trainName.toLowerCase();
  for (const record of TRAIN_TRANSLATIONS) {
    if (
      (record.names.en && lower.includes(record.names.en.toLowerCase().slice(0, 8))) ||
      record.numbers.some(num => lower.includes(num.toLowerCase()))
    ) {
      if (record.names[lang]) {
        return record.names[lang]!;
      }
    }
  }

  // Fallback heuristics for common terms in Indian Railways
  if (lang === 'hi') {
    let trans = trainName;
    trans = trans.replace(/Vande Bharat/gi, 'वंदे भारत');
    trans = trans.replace(/Shatabdi/gi, 'शताब्दी');
    trans = trans.replace(/Rajdhani/gi, 'राजधानी');
    trans = trans.replace(/Humsafar/gi, 'हमसफ़र');
    trans = trans.replace(/Superfast/gi, 'सुपरफास्ट');
    trans = trans.replace(/Express/gi, 'एक्सप्रेस');
    trans = trans.replace(/Freight/gi, 'मालगाड़ी');
    trans = trans.replace(/Rake/gi, 'रेक');
    trans = trans.replace(/Up\b/gi, 'अप');
    trans = trans.replace(/Down\b/gi, 'डाउन');
    trans = trans.replace(/Coal/gi, 'कोयला');
    trans = trans.replace(/Heavy Haul/gi, 'हैवी हॉल');
    trans = trans.replace(/Container/gi, 'कंटेनर');
    return trans;
  }

  return trainName;
}

